"""Deterministic citation metadata for source-grounded document answers.

Citation IDs are assigned by program code, not generated by the LLM.
Validation checks provenance integrity and valid reference IDs; it does
NOT establish semantic claim-level entailment or factual faithfulness.
"""

from dataclasses import dataclass
import re

from app.rag.reranker import RerankedHit


_CITATION_PATTERN = re.compile(r"\[S(\d+)\]")


@dataclass(frozen=True, slots=True)
class EvidenceSource:
    id: str
    document_id: str
    chunk_id: str
    filename: str
    page: int | None
    section: str | None
    evidence: str
    reranker_score: float


@dataclass(frozen=True, slots=True)
class CitationCheck:
    used_ids: tuple[str, ...]
    invalid_ids: tuple[str, ...]
    valid: bool


def build_sources(
    results: list[RerankedHit], *, max_evidence_chars: int = 160
) -> list[EvidenceSource]:
    """Construct bounded source objects and stable per-answer [S1] IDs."""
    if max_evidence_chars <= 0:
        raise ValueError("max_evidence_chars must be positive")
    sources: list[EvidenceSource] = []
    for index, result in enumerate(results, start=1):
        hit = result.hit
        sources.append(
            EvidenceSource(
                id=f"S{index}",
                document_id=hit.document_id,
                chunk_id=hit.chunk_id,
                filename=hit.filename,
                page=hit.page,
                section=hit.section,
                evidence=hit.text[:max_evidence_chars],
                reranker_score=result.reranker_score,
            )
        )
    return sources


def format_evidence(sources: list[EvidenceSource]) -> str:
    """Serialize sources as data; document text is untrusted."""
    parts: list[str] = []
    for source in sources:
        location = (
            f"第{source.page}页" if source.page is not None
            else (f"章节:{source.section}" if source.section else "页码未知")
        )
        parts.append(
            f"[{source.id}] 文件={source.filename!r} 位置={location}\n"
            f"引用内容：{source.evidence}"
        )
    return "\n\n".join(parts)


def validate_answer_citations(
    answer: str,
    sources: list[EvidenceSource],
    *,
    require_at_least_one: bool = True,
) -> CitationCheck:
    """Validate referenced IDs; unknown IDs and absent citations fail closed."""
    ids = tuple(dict.fromkeys(f"S{match}" for match in _CITATION_PATTERN.findall(answer)))
    allowed = {source.id for source in sources}
    invalid = tuple(source_id for source_id in ids if source_id not in allowed)
    valid = not invalid and (bool(ids) or not require_at_least_one)
    return CitationCheck(used_ids=ids, invalid_ids=invalid, valid=valid)
